def get_text(key: str, lang: str = "uz", **kwargs) -> str:
    """Get localized text by key."""
    text = TEXTS.get(lang, TEXTS["uz"]).get(key, TEXTS["uz"].get(key, key))
    if kwargs:
        text = text.format(**kwargs)
    return text
